"""Shell tab-completion script generation for evalyn CLI.

Generates bash, zsh, and fish completion scripts from a static command/flag
registry. No external dependencies - scripts are emitted as plain strings.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, List

# ---------------------------------------------------------------------------
# Data model
# ---------------------------------------------------------------------------


@dataclass
class CompletionConfig:
    """Configuration for shell completion generation."""

    shell: str  # "bash", "zsh", or "fish"
    commands: list[str] = field(default_factory=list)
    flags: dict[str, list[str]] = field(default_factory=dict)

    def as_dict(self) -> dict[str, Any]:
        return {
            "shell": self.shell,
            "commands": list(self.commands),
            "flags": {k: list(v) for k, v in self.flags.items()},
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> CompletionConfig:
        return cls(
            shell=data["shell"],
            commands=list(data.get("commands", [])),
            flags={k: list(v) for k, v in data.get("flags", {}).items()},
        )


